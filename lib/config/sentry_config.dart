/// Конфиг крашрепортинга на self-hosted Bugsink (Sentry-совместимый бэкенд на
/// нашем VPS — замена Firebase Crashlytics в рамках ухода с Firebase).
///
/// DSN — это НЕ секрет: публичный ключ проекта, он и должен жить в клиенте
/// (как и DSN в любом Sentry-приложении).
///
/// **Адрес обязан быть HTTPS через `bugsink.togetherly.day`.** Раньше здесь
/// стоял прямой `http://77.91.95.34:8000`, а 25 июля на VPS включили ufw, где
/// открыты только 22, 80, 443, 8443 и 8095. Порт 8000 снаружи закрылся, и
/// краши перестали доходить: в Bugsink нет ни одного события новее 22 июля и
/// ни одной версии свежее 1.17.0, хотя в проде уже 1.18.1. Приём по HTTPS
/// проксирует Caddy (блок `bugsink.togetherly.day` → 127.0.0.1:8000).
class SentryConfig {
  /// Свой Sentry/Bugsink: `--dart-define=SENTRY_DSN=...`. Пусто — отчёты об
  /// ошибках никуда не уходят.
  static const String dsn = String.fromEnvironment('SENTRY_DSN');
}
